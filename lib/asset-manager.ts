/**
 * Strict 3-Tier Filtering & Auto-Folder Creation Pipeline Engine
 * 
 * Step 1 (Search Box): User types query (e.g., "l sofa")
 * Step 2 (Category Dropdown): User selects Category (e.g. "Living Room")
 * Step 3 (Material Dropdown): User selects Material (e.g. "Fabric")
 * Step 4 (Output/Result):
 *   - Retrieve matching photos & videos, sorted by price (asc / desc).
 *   - If not found, auto-generate folder /{Category}/{Material}/{ItemName}/
 */
export function execute3TierPipeline(
  query: string,
  category: AssetCategory,
  material: AssetMaterial,
  priceSort: PriceSortOrder = "asc",
  assets: MediaAsset[] = DEFAULT_REPOSITORY_ASSETS,
  folders: RepositoryFolder[] = []
): {
  pipelineResult: PipelineResult;
  updatedFolders: RepositoryFolder[];
  newFolderCreated: RepositoryFolder | null;
} {
  const canonicalItem = normalizeItemName(query);
  const expectedFolderPath = buildDirectoryPath(category, material, canonicalItem);

  // 1. Filter assets strictly matching Category & Material
  const categoryAndMaterialMatches = assets.filter(
    (a) => a.category === category && a.material === material
  );

  // 2. Filter by search query within this slice
  const matchedAssets = categoryAndMaterialMatches.filter((a) =>
    matchesSearchQuery(a, query)
  );

  // 3. Sort by Price (Ascending or Descending)
  matchedAssets.sort((a, b) => {
    return priceSort === "asc" ? a.price - b.price : b.price - a.price;
  });

  // 4. Check folder existence in registry
  const existingFolder = folders.find((f) => f.path.toLowerCase() === expectedFolderPath.toLowerCase());
  const folderExists = Boolean(existingFolder) || matchedAssets.length > 0;

  let newFolderCreated: RepositoryFolder | null = null;
  const updatedFolders = [...folders];

  // 5. AUTO-FOLDER CREATION LOGIC:
  // If no assets exist and folder not yet registered, auto-generate folder in repository!
  if (!folderExists && query.trim().length > 0) {
    newFolderCreated = {
      id: "fld_" + Date.now() + "_" + Math.random().toString(36).slice(2, 6),
      path: expectedFolderPath,
      category,
      material,
      itemName: canonicalItem,
      assetCount: 0,
      createdAt: new Date().toISOString(),
      isAutoGenerated: true,
    };
    updatedFolders.push(newFolderCreated);
  }

  const pipelineResult: PipelineResult = {
    query,
    category,
    material,
    folderPath: expectedFolderPath,
    folderExists: folderExists || Boolean(newFolderCreated),
    folderAutoGenerated: Boolean(newFolderCreated),
    matchedAssets,
    totalMatches: matchedAssets.length,
    priceSort,
  };

  return {
    pipelineResult,
    updatedFolders,
    newFolderCreated,
  };
}
